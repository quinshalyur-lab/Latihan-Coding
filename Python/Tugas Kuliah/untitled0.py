import math
import timeit
import inspect


NAMA_TOKO = "TOKO KUE MANIS"
DISKON_MEMBER = 5
BIAYA_ADMIN_QRIS = 2500
ONGKIR_PER_100M = 200
LEBAR_STRUK = 40

# Kunci = nomor menu, nilai = (nama kue, harga)
MENU = {
    1: ("Cookies Matcha", 10000),
    2: ("Brownies Fudgy", 40000),
    3: ("Cookies Coklat", 10000),
    4: ("Bolu Gulung", 45000),
    5: ("Donat Kentang", 25000),
}

ATURAN_DISKON = [
    (300000, 15),
    (150000, 10),
    (50000, 5),
    (0, 0),
]


def rupiah(angka):
    """Mengubah 15000 menjadi 'Rp15.000'."""
    return f"Rp{angka:,.0f}".replace(",", ".")


def garis(karakter="-", lebar=LEBAR_STRUK):
    """Mencetak satu baris garis pemisah."""
    print(karakter * lebar)


def baris_struk(label, nilai):
    """Mencetak satu baris struk: tulisan di kiri, angka di kanan."""
    print(f"{label:<22}{nilai:>18}")


def tampilkan_judul_toko():
    """Menampilkan papan nama toko."""
    garis("=")
    print(f"SELAMAT DATANG DI {NAMA_TOKO}".center(LEBAR_STRUK))
    garis("=")


def tampilkan_promo():
    """Memberi tahu pembeli promo diskon yang berlaku."""
    print("PROMO DISKON:")
    batas_terkecil = min(b for b, p in ATURAN_DISKON if b > 0)
    print(f"  - Belanja di bawah {rupiah(batas_terkecil)} tidak dapat diskon")
    for batas, persen in ATURAN_DISKON:
        if batas > 0:
            print(f"  - Belanja minimal {rupiah(batas)} dapat diskon {persen}%")
    print(f"  - Member dapat TAMBAHAN diskon {DISKON_MEMBER}%")
    print("  (diskon dihitung dari total belanja, sebelum ongkir & admin)")


def tampilkan_menu():
    """Menampilkan daftar kue beserta harganya."""
    print()
    garis("=")
    print("DAFTAR MENU".center(LEBAR_STRUK))
    garis("=")

    for nomor, (nama, harga) in MENU.items():
        print(f"{nomor}. {nama:<15}{rupiah(harga):>12}")

    garis("=")


def input_nama():
    """Meminta nama pelanggan. Tidak boleh kosong."""
    while True:
        nama = input("Silakan ketik nama kamu, lalu tekan Enter: ").strip()

        if nama == "":
            print("  [!] Nama tidak boleh kosong.")
        else:
            return nama.title()


def input_angka(pesan):
    """Meminta angka bulat. Menolak huruf dan angka negatif."""
    while True:
        teks = input(pesan).strip()

        if not teks.isdigit():
            print("  [!] Masukkan angka bulat positif saja.")
        else:
            return int(teks)


def input_ya_tidak(pesan):
    """Meminta jawaban y (ya) atau n (tidak)."""
    while True:
        jawab = input(f"{pesan} [Y/N]: ").strip().lower()

        if jawab == "y":
            return True
        elif jawab == "n":
            return False
        else:
            print("  [!] Jawab dengan Y atau N saja.")


def input_pesanan():
    """Mengisi keranjang. Hasilnya kamus {nomor menu: jumlah}."""
    keranjang = {}

    print()
    print("CARA MEMESAN:")
    print("  1. Ketik NOMOR menu (contoh: 1)")
    print("  2. Lalu ketik JUMLAH-nya, misalnya 2")
    print("  3. Mau kue lain? Ulangi langkah 1 dan 2")
    print("  4. Kalau pesanan sudah cukup, ketik: selesai")

    while True:
        pilihan = input("\nNomor kue (atau ketik selesai): ").strip().lower()

        if pilihan == "selesai":
            if len(keranjang) == 0:
                print("  [!] Belum ada pesanan, pilih minimal 1 kue.")
                continue
            break

        if not pilihan.isdigit():
            print("  [!] Ketik nomor menu saja, atau 'selesai'.")
            continue

        nomor = int(pilihan)
        if nomor not in MENU:
            print(f"  [!] Nomor {nomor} tidak ada. Pilih 1 sampai {len(MENU)}.")
            continue

        nama_kue = MENU[nomor][0]
        jumlah = input_angka(f"Jumlah {nama_kue}: ")

        if jumlah == 0:
            print("  [!] Jumlah harus lebih dari 0.")
        else:
            keranjang[nomor] = keranjang.get(nomor, 0) + jumlah
            print(f"  + {jumlah} {nama_kue} ditambahkan.")

    return keranjang


def hitung_subtotal(keranjang):
    """Menjumlahkan harga x jumlah semua kue di keranjang."""
    subtotal = 0
    for nomor, jumlah in keranjang.items():
        harga = MENU[nomor][1]
        subtotal += harga * jumlah
    return subtotal


def hitung_ongkir(jarak_meter):
    """Ongkir Rp200 per 100 meter. Sisa jarak dibulatkan KE ATAS."""
    jumlah_blok = math.ceil(jarak_meter / 100)
    return jumlah_blok * ONGKIR_PER_100M


def diskon_ifelif(subtotal):
    """Cara 1: aturan ditulis langsung sebagai if-elif."""
    if subtotal >= 300000:
        return 15
    elif subtotal >= 150000:
        return 10
    elif subtotal >= 50000:
        return 5
    else:
        return 0


def diskon_tabel(subtotal):
    """Cara 2: aturan disimpan di tabel ATURAN_DISKON, lalu dibaca satu-satu."""
    for batas, persen in ATURAN_DISKON:
        if subtotal >= batas:
            return persen


def cetak_struk(nama, keranjang, subtotal, persen, diskon,
                member, diskon_member,
                pakai_qris, admin, antar, jarak, ongkir, total):
    """Mencetak struk belanja."""
    print()
    garis("=")
    print("STRUK BELANJA".center(LEBAR_STRUK))
    garis("=")
    print(f"Pelanggan : {nama}")
    garis()

    for nomor, jumlah in keranjang.items():
        nama_kue, harga = MENU[nomor]
        print(nama_kue)
        print(f"  {jumlah} x {rupiah(harga):<10}{rupiah(jumlah * harga):>20}")

    garis()
    baris_struk("Subtotal", rupiah(subtotal))
    if persen > 0:
        baris_struk(f"Diskon {persen}%", "-" + rupiah(diskon))
    if member:
        baris_struk(f"Diskon member {DISKON_MEMBER}%", "-" + rupiah(diskon_member))

    if pakai_qris:
        baris_struk("Biaya admin QRIS", rupiah(admin))
    if antar:
        baris_struk(f"Ongkir ({jarak} m)", rupiah(ongkir))

    garis("=")
    baris_struk("TOTAL BAYAR", rupiah(total))
    garis("=")
    print("Terima kasih sudah berbelanja!".center(LEBAR_STRUK))
    garis("=")


def hitung_baris(fungsi):
    """Menghitung jumlah baris kode sebuah fungsi."""
    try:
        return len(inspect.getsource(fungsi).splitlines())
    except (OSError, TypeError):
        return "-"


def uji_kecepatan(subtotal):
    """Mengadu CARA 1 vs CARA 2 memakai subtotal milik pembeli ini."""
    ulang = 100000
    waktu_ifelif = timeit.timeit(lambda: diskon_ifelif(subtotal), number=ulang)
    waktu_tabel = timeit.timeit(lambda: diskon_tabel(subtotal), number=ulang)

    hasil_ifelif = diskon_ifelif(subtotal)
    hasil_tabel = diskon_tabel(subtotal)
    sama = (hasil_ifelif == hasil_tabel)

    print()
    garis("*")
    print("UJI KECEPATAN HITUNG DISKON".center(LEBAR_STRUK))
    garis("*")
    print(f"Subtotal belanja : {rupiah(subtotal)}")
    print(f"Diskon if-elif   : {hasil_ifelif}%   waktu {waktu_ifelif:.4f} detik")
    print(f"Diskon tabel     : {hasil_tabel}%   waktu {waktu_tabel:.4f} detik")
    print(f"(masing-masing dijalankan {ulang:,} kali)".replace(",", "."))
    print("Hasil kedua cara sama" if sama else "[!] Hasil kedua cara BEDA!")
    garis("*")

    return waktu_ifelif, waktu_tabel, sama


def jalankan_kasir():
    tampilkan_judul_toko()
    nama = input_nama()
    print(f"\nHalo, {nama}! Silakan lihat daftar menu kami di bawah ini.")

    tampilkan_menu()
    print()
    tampilkan_promo()
    keranjang = input_pesanan()

    subtotal = hitung_subtotal(keranjang)
    persen = diskon_ifelif(subtotal)
    diskon = subtotal * persen / 100

    print()
    member = input_ya_tidak("Apakah kamu member toko kami?")
    diskon_member = 0
    if member:
        diskon_member = subtotal * DISKON_MEMBER / 100

    print("\nPEMBAYARAN & PENGIRIMAN")
    print(f"  - Bayar QRIS dikenakan biaya admin {rupiah(BIAYA_ADMIN_QRIS)}")
    print(f"  - Antar ke rumah dikenakan ongkir {rupiah(ONGKIR_PER_100M)} per 100 meter")
    pakai_qris = input_ya_tidak("Mau bayar pakai QRIS?")
    admin = BIAYA_ADMIN_QRIS if pakai_qris else 0

    antar = input_ya_tidak("Mau diantar ke rumah?")
    jarak = 0
    ongkir = 0
    if antar:
        jarak = input_angka("Jarak ke rumah dalam METER (contoh: 250): ")
        ongkir = hitung_ongkir(jarak)

    total = subtotal - diskon - diskon_member + admin + ongkir

    waktu_a, waktu_b, sama = uji_kecepatan(subtotal)

    cetak_struk(nama, keranjang, subtotal, persen, diskon,
                member, diskon_member,
                pakai_qris, admin, antar, jarak, ongkir, total)

    return {"nama": nama, "subtotal": subtotal,
            "waktu_ifelif": waktu_a, "waktu_tabel": waktu_b, "sama": sama}


def tampilkan_rekap(riwayat):
    """Menampilkan tabel perbandingan dari semua transaksi hari ini."""
    lebar = 52
    print()
    garis("=", lebar)
    print("REKAP UJI KECEPATAN SEMUA TRANSAKSI".center(lebar))
    garis("=", lebar)
    print(f"{'No':<4}{'Pelanggan':<12}{'Subtotal':>12}{'if-elif':>12}{'Tabel':>12}")
    garis("-", lebar)

    total_a = 0
    total_b = 0
    for nomor, catatan in enumerate(riwayat, start=1):
        print(f"{nomor:<4}{catatan['nama'][:10]:<12}"
              f"{rupiah(catatan['subtotal']):>12}"
              f"{catatan['waktu_ifelif']:>12.4f}"
              f"{catatan['waktu_tabel']:>12.4f}")
        total_a += catatan["waktu_ifelif"]
        total_b += catatan["waktu_tabel"]

    garis("-", lebar)
    print(f"{'TOTAL WAKTU (detik)':<28}{total_a:>12.4f}{total_b:>12.4f}")
    print(f"{'JUMLAH BARIS KODE':<28}{hitung_baris(diskon_ifelif):>12}"
          f"{hitung_baris(diskon_tabel):>12}")
    garis("=", lebar)
    print(f"Jumlah transaksi : {len(riwayat)}")
    if total_a < total_b:
        print("Lebih cepat      : if-elif")
    else:
        print("Lebih cepat      : tabel")
    print("Catatan: Cara 2 juga memakai tabel ATURAN_DISKON (4 baris) di bagian data.")


def main():
    riwayat = []

    while True:
        catatan = jalankan_kasir()
        riwayat.append(catatan)

        if not input_ya_tidak("Ada transaksi lagi?"):
            break

    tampilkan_rekap(riwayat)


if __name__ == "__main__":
    main()